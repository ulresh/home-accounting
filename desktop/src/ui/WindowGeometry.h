#pragma once
#include <QString>

class QWidget;

namespace ha::ui {

// Запоминать положение, размер и распахнутость окна — между открытиями окна
// и между запусками приложения. Хранилище — QSettings (на Linux это
// ~/.config/<организация>/<приложение>.conf), группа "windows", ключ key.
// В файлах данных геометрия не хранится: она привязана к экрану конкретной
// машины и не должна ни синхронизироваться, ни переезжать вместе с базой.
//
// Вызывать в конце конструктора окна, ПОСЛЕ resize()/setMinimumWidth() по
// умолчанию: если сохранённого состояния нет (или оно от несовместимой версии
// Qt), останется умолчание. Сохранение — само, при закрытии/скрытии окна и при
// выходе из приложения; отдельно ничего вызывать не нужно.
void rememberGeometry(QWidget* w, const QString& key);

}
